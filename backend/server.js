/* =========================================================
   GOOGLE LOGIN — STEP 1: REDIRECT TO GOOGLE
========================================================= */

app.get("/auth/google", (req, res) => {
  if (!GOOGLE_CLIENT_ID || !GOOGLE_CLIENT_SECRET) {
    console.error("Google OAuth credentials are missing.");

    return res.status(503).json({
      message: "Google sign-in is not configured on the backend.",
    });
  }

  // Remove expired states.
  const now = Date.now();

  for (const [key, expiresAt] of googleStates.entries()) {
    if (expiresAt < now) {
      googleStates.delete(key);
    }
  }

  const state = crypto.randomBytes(32).toString("hex");

  // State expires after 10 minutes.
  googleStates.set(state, now + 10 * 60 * 1000);

  const params = new URLSearchParams({
    client_id: GOOGLE_CLIENT_ID,
    redirect_uri: GOOGLE_REDIRECT_URI,
    response_type: "code",
    scope: "openid email profile",
    state,
    prompt: "select_account",
  });

  const googleURL =
    "https://accounts.google.com/o/oauth2/v2/auth?" +
    params.toString();

  console.log("Redirecting user to Google OAuth.");

  return res.redirect(googleURL);
});

/* =========================================================
   GOOGLE LOGIN — STEP 2: GOOGLE CALLBACK
========================================================= */

app.get("/auth/google/callback", async (req, res) => {
  const { code, state, error } = req.query;

  const expiresAt =
    typeof state === "string" ? googleStates.get(state) : undefined;

  if (typeof state === "string") {
    googleStates.delete(state);
  }

  if (
    error ||
    typeof code !== "string" ||
    typeof state !== "string" ||
    !expiresAt ||
    expiresAt < Date.now()
  ) {
    console.error("Invalid, expired, or cancelled Google OAuth request.");

    return res.redirect(frontendRedirect("error"));
  }

  if (!GOOGLE_CLIENT_ID || !GOOGLE_CLIENT_SECRET) {
    return res.redirect(frontendRedirect("error"));
  }

  try {
    /* Exchange the authorization code for a token. */
    const tokenResponse = await fetch(
      "https://oauth2.googleapis.com/token",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/x-www-form-urlencoded",
        },
        body: new URLSearchParams({
          code,
          client_id: GOOGLE_CLIENT_ID,
          client_secret: GOOGLE_CLIENT_SECRET,
          redirect_uri: GOOGLE_REDIRECT_URI,
          grant_type: "authorization_code",
        }),
      }
    );

    if (!tokenResponse.ok) {
      const errorText = await tokenResponse.text();

      console.error("Google token request failed:", errorText);

      return res.redirect(frontendRedirect("error"));
    }

    const tokenData = await tokenResponse.json();

    if (!tokenData.access_token) {
      console.error("Google did not return an access token.");

      return res.redirect(frontendRedirect("error"));
    }

    /* Retrieve the Google profile. */
    const profileResponse = await fetch(
      "https://www.googleapis.com/oauth2/v3/userinfo",
      {
        headers: {
          Authorization: `Bearer ${tokenData.access_token}`,
        },
      }
    );

    if (!profileResponse.ok) {
      console.error("Could not retrieve the Google user profile.");

      return res.redirect(frontendRedirect("error"));
    }

    const profile = await profileResponse.json();

    if (
      !profile.email ||
      profile.email_verified !== true
    ) {
      console.error("Google account does not have a verified email.");

      return res.redirect(frontendRedirect("error"));
    }

    const cleanEmail = profile.email.trim().toLowerCase();
    const userName =
      (profile.name || cleanEmail.split("@")[0]).trim().slice(0, 100);

    await waitForDatabase();

    /* Find an existing user. PostgreSQL uses $1 placeholders. */
    const existingResult = await db.query(
      "SELECT id, name, email FROM public.users WHERE email = $1",
      [cleanEmail]
    );

    let user;

    if (existingResult.rows.length > 0) {
      user = existingResult.rows[0];

      console.log("Existing Google user signed in:", cleanEmail);
    } else {
      /* Create a user with a random, unusable-as-known-password value. */
      const randomPassword = crypto.randomBytes(32).toString("hex");
      const hashedPassword = await bcrypt.hash(randomPassword, 10);

      const insertResult = await db.query(
        `INSERT INTO public.users (name, email, password)
         VALUES ($1, $2, $3)
         ON CONFLICT (email) DO NOTHING
         RETURNING id, name, email`,
        [userName, cleanEmail, hashedPassword]
      );

      if (insertResult.rows.length > 0) {
        user = insertResult.rows[0];
        console.log("New Google user created:", cleanEmail);
      } else {
        // Another request may have created the same email concurrently.
        const retryResult = await db.query(
          "SELECT id, name, email FROM public.users WHERE email = $1",
          [cleanEmail]
        );

        if (retryResult.rows.length === 0) {
          throw new Error("Could not retrieve the Google user after creation.");
        }

        user = retryResult.rows[0];
      }
    }

    /*
      Compatibility with the existing frontend:
      it expects ?google=success&name=...
      This redirect alone is NOT a secure authenticated session.
    */
    return res.redirect(frontendRedirect("success", user.name));
  } catch (err) {
    console.error("Google OAuth error:", err.message);

    return res.redirect(frontendRedirect("error"));
  }
});

/* =========================================================
   REGISTER
========================================================= */

app.post("/register", async (req, res) => {
  try {
    const { name, email, password } = req.body || {};

    if (
      typeof name !== "string" ||
      typeof email !== "string" ||
      typeof password !== "string" ||
      !name.trim() ||
      !email.trim() ||
      !password
    ) {
      return res.status(400).json({
        message: "Name, email and password are required.",
      });
    }

    if (password.length < 6) {
      return res.status(400).json({
        message: "Password must be at least 6 characters.",
      });
    }

    const cleanName = name.trim().slice(0, 100);
    const cleanEmail = email.trim().toLowerCase();

    if (cleanEmail.length > 255) {
      return res.status(400).json({
        message: "Email address is too long.",
      });
    }

    await waitForDatabase();

    const existingResult = await db.query(
      "SELECT id FROM public.users WHERE email = $1",
      [cleanEmail]
    );

    if (existingResult.rows.length > 0) {
      return res.status(409).json({
        message: "Email already registered.",
      });
    }

    const hashedPassword = await bcrypt.hash(password, 10);

    const insertResult = await db.query(
      `INSERT INTO public.users (name, email, password)
       VALUES ($1, $2, $3)
       ON CONFLICT (email) DO NOTHING
       RETURNING id`,
      [cleanName, cleanEmail, hashedPassword]
    );

    if (insertResult.rows.length === 0) {
      return res.status(409).json({
        message: "Email already registered.",
      });
    }

    console.log("New user registered:", cleanEmail);

    return res.status(201).json({
      message: "Registration successful.",
      userId: insertResult.rows[0].id,
    });
  } catch (err) {
    console.error("Registration error:", err.message);

    return res.status(500).json({
      message: "Registration failed. Please try again.",
    });
  }
});

/* =========================================================
   EMAIL AND PASSWORD LOGIN
========================================================= */

app.post("/login", async (req, res) => {
  try {
    const { email, password } = req.body || {};

    if (
      typeof email !== "string" ||
      typeof password !== "string" ||
      !email.trim() ||
      !password
    ) {
      return res.status(400).json({
        message: "Email and password are required.",
      });
    }

    const cleanEmail = email.trim().toLowerCase();

    await waitForDatabase();

    const result = await db.query(
      "SELECT id, name, email, password FROM public.users WHERE email = $1",
      [cleanEmail]
    );

    if (result.rows.length === 0) {
      return res.status(401).json({
        message: "Invalid email or password.",
      });
    }

    const user = result.rows[0];
    const passwordMatch = await bcrypt.compare(
      password,
      user.password
    );

    if (!passwordMatch) {
      return res.status(401).json({
        message: "Invalid email or password.",
      });
    }

    console.log("User logged in:", user.email);

    return res.status(200).json({
      message: "Login successful.",
      user: {
        id: user.id,
        name: user.name,
        email: user.email,
      },
    });
  } catch (err) {
    console.error("Login error:", err.message);

    return res.status(500).json({
      message: "Login failed. Please try again.",
    });
  }
});

