app.get("/auth/google/callback", async (req, res) => {
  const { code, state, error } = req.query;

  const expiresAt = googleStates.get(state);
  googleStates.delete(state);

  if (
    error ||
    !code ||
    !expiresAt ||
    expiresAt < Date.now()
  ) {
    console.error("❌ Invalid Google OAuth request.");
    return res.redirect(frontendRedirect("error"));
  }

  try {
    // Exchange authorization code for token
    const tokenResponse = await fetch(
      "https://oauth2.googleapis.com/token",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/x-www-form-urlencoded",
        },
        body: new URLSearchParams({
          code,
          client_id: GOOGLE_CLIENT_ID,
          client_secret: GOOGLE_CLIENT_SECRET,
          redirect_uri: GOOGLE_REDIRECT_URI,
          grant_type: "authorization_code",
        }),
      }
    );

    if (!tokenResponse.ok) {
      const errorText = await tokenResponse.text();
      console.error("Google token error:", errorText);
      throw new Error("Google token request failed");
    }

    const tokenData = await tokenResponse.json();
    const accessToken = tokenData.access_token;

    if (!accessToken) {
      throw new Error("Google access token missing");
    }

    // Retrieve Google profile
    const profileResponse = await fetch(
      "https://www.googleapis.com/oauth2/v2/userinfo",
      {
        headers: {
          Authorization: `Bearer ${accessToken}`,
        },
      }
    );

    if (!profileResponse.ok) {
      throw new Error("Google profile request failed");
    }

    const profile = await profileResponse.json();

    if (!profile.email || !profile.verified_email) {
      throw new Error("Google email is not verified");
    }

    const email = profile.email.trim().toLowerCase();
    const googleId = profile.id;
    const userName = profile.name || email.split("@")[0];

    console.log("✅ Google user:", email);

    // Check existing user
    const existingUser = await db.query(
      "SELECT id, name, email FROM public.users WHERE email = $1",
      [email]
    );

    if (existingUser.rows.length > 0) {
      const user = existingUser.rows[0];

      // Link Google ID to existing account
      await db.query(
        `UPDATE public.users
         SET google_id = COALESCE(google_id, $1)
         WHERE id = $2`,
        [googleId, user.id]
      );

      console.log("✅ Existing Google user logged in.");

      return res.redirect(
        frontendRedirect("success", user.name)
      );
    }

    // Create new Google user
    const generatedPassword = await bcrypt.hash(
      crypto.randomBytes(32).toString("hex"),
      10
    );

    const newUser = await db.query(
      `INSERT INTO public.users
       (name, email, password, google_id)
       VALUES ($1, $2, $3, $4)
       RETURNING id, name, email`,
      [userName, email, generatedPassword, googleId]
    );

    console.log(
      "✅ New Google user created:",
      newUser.rows[0].email
    );

    return res.redirect(
      frontendRedirect("success", newUser.rows[0].name)
    );

  } catch (error) {
    console.error("❌ Google OAuth error:", error.message);
    return res.redirect(frontendRedirect("error"));
  }
});

