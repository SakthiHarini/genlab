
require("dotenv").config();

const express = require("express");
const cors = require("cors");
const { Pool } = require("pg");
const bcrypt = require("bcrypt");
const crypto = require("crypto");

const app = express();

/* =========================================================
   CONFIGURATION
========================================================= */

const PORT = process.env.PORT || 5000;

const FRONTEND_URL = (
  process.env.FRONTEND_URL || "https://sakthi-mauve.vercel.app"
).replace(/\/+$/, "");

const GOOGLE_CLIENT_ID = process.env.GOOGLE_CLIENT_ID;
const GOOGLE_CLIENT_SECRET = process.env.GOOGLE_CLIENT_SECRET;

const GOOGLE_REDIRECT_URI =
  process.env.GOOGLE_REDIRECT_URI ||
  "https://genlab-o7dn.onrender.com/auth/google/callback";

const allowedOrigins = [
  "http://localhost:5173",
  "http://localhost:5174",
  "https://sakthi-mauve.vercel.app",
  "https://pl13pz9m-5173.inc1.devtunnels.ms",
];

/* =========================================================
   SUPABASE POSTGRESQL CONNECTION
========================================================= */

const db = new Pool({
  host: process.env.DB_HOST,
  port: Number(process.env.DB_PORT || 5432),
  user: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  database: process.env.DB_NAME || "postgres",
  ssl: {
    rejectUnauthorized: false,
  },
  connectionTimeoutMillis: 10000,
  idleTimeoutMillis: 30000,
  max: 5,
});

db.on("error", (err) => {
  console.error("Unexpected PostgreSQL pool error:", err.message);
});

/* =========================================================
   GOOGLE OAUTH STATE
========================================================= */

const googleStates = new Map();

/* =========================================================
   MIDDLEWARE
========================================================= */

app.use(
  cors({
    origin(origin, callback) {
      // Requests without an Origin include health checks and server-to-server calls.
      if (!origin || allowedOrigins.includes(origin)) {
        return callback(null, true);
      }

      return callback(new Error("Origin not allowed by CORS"));
    },
    methods: ["GET", "POST", "PUT", "DELETE", "OPTIONS"],
    allowedHeaders: ["Content-Type", "Authorization"],
  })
);

app.use(express.json({ limit: "1mb" }));

/* =========================================================
   DATABASE INITIALIZATION
========================================================= */

async function initializeDatabase() {
  const client = await db.connect();

  try {
    const result = await client.query("SELECT current_database()");
    console.log(
      "PostgreSQL connected. Database:",
      result.rows[0].current_database
    );

    await client.query(`
      CREATE TABLE IF NOT EXISTS public.users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        email VARCHAR(255) NOT NULL UNIQUE,
        password VARCHAR(255) NOT NULL
      )
    `);

    console.log("Supabase users table is ready.");
  } finally {
    client.release();
  }
}

// Start initialization without preventing the HTTP server from starting
// if the database is temporarily unavailable.
const databaseReady = initializeDatabase().catch((err) => {
  console.error("Supabase PostgreSQL connection/setup failed:", err.message);
});

/* =========================================================
   HELPER FUNCTIONS
========================================================= */

function frontendRedirect(status, name) {
  const params = new URLSearchParams({ google: status });

  if (name) {
    params.set("name", name);
  }

  return `${FRONTEND_URL}/?${params.toString()}`;
}

async function waitForDatabase() {
  await databaseReady;
}

